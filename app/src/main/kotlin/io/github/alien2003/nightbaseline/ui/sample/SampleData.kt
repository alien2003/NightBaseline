// The synthetic person and dates are hand-picked sample numbers, like core-algo's SyntheticNights.
@file:Suppress("MagicNumber")

package io.github.alien2003.nightbaseline.ui.sample

import io.github.alien2003.nightbaseline.algo.AlgoParams
import io.github.alien2003.nightbaseline.algo.MetricId
import io.github.alien2003.nightbaseline.algo.NightEvaluation
import io.github.alien2003.nightbaseline.algo.NightSummary
import io.github.alien2003.nightbaseline.algo.Pipeline
import io.github.alien2003.nightbaseline.algo.SyntheticNights
import io.github.alien2003.nightbaseline.ui.home.HomeState
import io.github.alien2003.nightbaseline.ui.model.BannerKind
import io.github.alien2003.nightbaseline.ui.model.ChartPeriod
import io.github.alien2003.nightbaseline.ui.model.ChartPointUi
import io.github.alien2003.nightbaseline.ui.model.MetricSeriesUi
import io.github.alien2003.nightbaseline.ui.model.MetricState
import io.github.alien2003.nightbaseline.ui.model.MetricUi
import io.github.alien2003.nightbaseline.ui.model.NightState
import io.github.alien2003.nightbaseline.ui.model.NightUi
import io.github.alien2003.nightbaseline.ui.model.NightUiMapper
import io.github.alien2003.nightbaseline.ui.model.RangeUi
import java.time.LocalDate
import java.time.ZoneOffset

/**
 * Synthetic data for previews, the component catalog, the placeholder Home and the screenshot tests. Everything is
 * generated by core-algo's [SyntheticNights] (fixed seed) and evaluated by the real [Pipeline]; no Health Connect data
 * is ever involved. Variants of a state that the generator does not happen to produce are derived from generated
 * nights by changing the state (still synthetic).
 */
object SampleData {
    /** Label used for the source app in sample copy (a neutral placeholder, not a real package). */
    const val SOURCE: String = "Demo watch"

    /** Wake date of the newest sample night. */
    val LAST_WAKE: LocalDate = LocalDate.of(2026, 11, 25)

    private const val NIGHTS = 120
    private const val EPISODE_LENGTH = 2
    private const val SEED = 11L
    private const val HRV_LEVEL = 46.0
    private const val SKIN_LEVEL = 34.2
    private val zone: ZoneOffset = ZoneOffset.ofHours(3)
    private val params = AlgoParams()

    private val generated: List<Pair<NightSummary, NightEvaluation>> by lazy {
        val generator =
            SyntheticNights(
                SyntheticNights.Config(
                    seed = SEED,
                    nights = NIGHTS,
                    firstWakeDate = LAST_WAKE.minusDays(NIGHTS - 1L),
                    offset = zone,
                    hrvLevel = HRV_LEVEL,
                    skinTempLevel = SKIN_LEVEL,
                    // An episode over the last two nights, so the newest night shows measurements that moved.
                    episodes = mapOf(NIGHTS - EPISODE_LENGTH to EPISODE_LENGTH, 70 to 3),
                ),
            )
        val nights = generator.generate()
        val (sessions, channels) = generator.flatten(nights)
        Pipeline.run(sessions, channels, params)
    }

    private val summaries: List<NightSummary> by lazy { generated.map { it.first } }

    /**
     * Every generated night as core-algo summary and evaluation, oldest first: what the daily work would store. The
     * integrated screenshots and the navigation tests fill fake repositories with it (synthetic, never real data).
     */
    val evaluated: List<Pair<NightSummary, NightEvaluation>> get() = generated

    /** The zone of the synthetic person (UTC+3). */
    val ZONE: ZoneOffset get() = zone

    /** Every evaluated sample night, oldest first. */
    val nights: List<NightUi> by lazy {
        generated.map { (summary, evaluation) -> NightUiMapper.night(summary, evaluation, params, summaries, zone = zone) }
    }

    /** The newest sample night. */
    val lastNight: NightUi by lazy { nights.last() }

    /** The newest night that has ranges for every metric (the base of the derived variants). */
    private val reference: NightUi by lazy {
        nights.last { night -> night.state.hasSummary && night.metrics.all { it.range != null && it.value != null } }
    }

    /** Last night with [count] metrics (2..6), registry order. */
    fun lastNight(count: Int): NightUi {
        val base = lastNight
        val metrics = base.metrics.take(count.coerceIn(2, base.metrics.size))
        return base.copy(metrics = metrics, deviating = metrics.count { it.state.moved }.coerceAtMost(base.deviating))
    }

    /** The newest night in [state]: a generated one if it exists, otherwise derived from a generated night. */
    fun night(state: NightState): NightUi =
        when (state) {
            NightState.AllWithin -> {
                withMetricStates(reference, NightState.AllWithin) { MetricState.Within }
            }

            NightState.SomeMoved -> {
                moved(1, NightState.SomeMoved)
            }

            NightState.Moved -> {
                moved(2, NightState.Moved)
            }

            NightState.Learning, NightState.LearningStart -> {
                learning(if (state == NightState.LearningStart) 0 else LEARNING_SAMPLE)
            }

            NightState.Short -> {
                withMetricStates(
                    reference,
                    NightState.Short,
                ) { MetricState.NotCompared }.copy(asleepMinutes = SHORT_MINUTES)
            }

            else -> {
                reference.copy(state = state, deviating = 0)
            }
        }

    /** A metric of the reference night in [state], with a value placed to match it. */
    fun metric(
        metric: MetricId,
        state: MetricState,
    ): MetricUi {
        val base = reference.metrics.first { it.metric == metric }
        return variant(base, state)
    }

    /** The first [count] metrics of the reference night, each in its usual state. */
    fun metrics(count: Int = 6): List<MetricUi> = reference.metrics.take(count)

    /** History of [metric] over the last [nights] calendar nights (gaps for nights without a value). */
    fun series(
        metric: MetricId,
        nights: Int,
    ): MetricSeriesUi {
        val byDate = this.nights.associateBy { it.wakeDate }
        val points =
            (nights - 1 downTo 0).map { back ->
                val date = LAST_WAKE.minusDays(back.toLong())
                val m = byDate[date]?.metrics?.firstOrNull { it.metric == metric }
                ChartPointUi(date, m?.value, m?.range, m?.state ?: MetricState.NoData)
            }
        return MetricSeriesUi(metric, points)
    }

    /** A series while learning: values without a range for the first [nights] nights. */
    fun learningSeries(
        metric: MetricId,
        nights: Int,
    ): MetricSeriesUi {
        val series = series(metric, nights)
        return series.copy(
            points =
                series.points.map {
                    it.copy(
                        range = null,
                        state =
                            if (it.value ==
                                null
                            ) {
                                MetricState.NoData
                            } else {
                                MetricState.Learning
                            },
                    )
                },
        )
    }

    /** The last [count] nights (newest last) for strips and lists. */
    fun recent(count: Int): List<NightUi> = nights.takeLast(count)

    /** Home on the newest sample night (or [night]), with 90-night series of every metric for the detail pane. */
    fun home(
        night: NightUi = lastNight,
        banner: BannerKind? = null,
    ): HomeState =
        HomeState(
            night = night,
            recent = recent(STRIP_NIGHTS),
            source = SOURCE,
            banner = banner,
            series = night.metrics.associate { it.metric to series(it.metric, ChartPeriod.Quarter.nights) },
        )

    private fun moved(
        count: Int,
        state: NightState,
    ): NightUi {
        val movable = listOf(MetricId.SLEEPING_HR, MetricId.RESPIRATORY_RATE)
        val night = withMetricStates(reference, state) { if (it.metric in movable.take(count)) MetricState.Higher else MetricState.Within }
        return night.copy(deviating = count)
    }

    private fun learning(nights: Int): NightUi {
        val night = withMetricStates(reference, if (nights == 0) NightState.LearningStart else NightState.Learning) { MetricState.Learning }
        return night.copy(
            historyNights = nights,
            metrics = night.metrics.map { it.copy(range = null, learnedNights = nights, value = if (nights == 0) null else it.value) },
            deviating = 0,
        )
    }

    private fun withMetricStates(
        base: NightUi,
        state: NightState,
        metricState: (MetricUi) -> MetricState,
    ): NightUi =
        base.copy(
            state = state,
            metrics = base.metrics.map { variant(it, metricState(it)) },
            deviating = 0,
        )

    /** [base] (with a range) moved into [state], keeping everything synthetic. */
    private fun variant(
        base: MetricUi,
        state: MetricState,
    ): MetricUi {
        val range = base.range ?: RangeUi(0.0, 1.0, 0.5)
        val width = range.high - range.low
        val value =
            when (state) {
                MetricState.Within, MetricState.NotCompared -> range.median + width * WITHIN_OFFSET
                MetricState.Higher, MetricState.SideIgnoredHigher -> range.high + width * OUTSIDE_OFFSET
                MetricState.Lower, MetricState.SideIgnoredLower -> range.low - width * OUTSIDE_OFFSET
                MetricState.Learning -> range.median
                else -> null
            }
        return base.copy(
            state = state,
            value = value,
            range =
                if (state == MetricState.NotProvided || state == MetricState.AccessOff ||
                    state == MetricState.Learning
                ) {
                    null
                } else {
                    range
                },
            learnedNights = if (state == MetricState.Learning) LEARNING_SAMPLE else 0,
            samples = if (state == MetricState.TooFew) FEW_SAMPLES else base.samples,
            coverage = if (state == MetricState.LowCoverage) LOW_COVERAGE else base.coverage,
        )
    }

    private const val LEARNING_SAMPLE = 4
    private const val STRIP_NIGHTS = 7
    private const val SHORT_MINUTES = 142.0
    private const val WITHIN_OFFSET = 0.12
    private const val OUTSIDE_OFFSET = 0.35
    private const val FEW_SAMPLES = 9
    private const val LOW_COVERAGE = 0.38
}
